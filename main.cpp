// ============================================================
//  随机模拟（验证通关率）
// ============================================================
void simulate(int totalGames) {
    mt19937 rng(42);
    uniform_int_distribution<int> dist(0, 2);
    int wins = 0, deaths = 0, totalSteps = 0;
    map<int, int> deathCounts;

    for (int g = 0; g < totalGames; g++) {
        int current = 1, steps = 0;
        while (true) {
            Node& n = G[current];
            if (n.isEnding) {
                if (n.isVictory) wins++;
                else { deaths++; deathCounts[current]++; }
                break;
            }
            current = n.choices[dist(rng)].target;
            steps++;
            if (steps > 500) { deaths++; break; }
        }
        totalSteps += steps;
    }

    cout << "\n========================================\n";
    cout << "  随机模拟结果（" << totalGames << " 次）\n";
    cout << "========================================\n";
    cout << "通关次数: " << wins << "\n";
    cout << "死亡次数: " << deaths << "\n";
    cout << "通关率:   " << 100.0 * wins / totalGames << "%\n";
    cout << "平均步数: " << (double)totalSteps / totalGames << "\n";
    cout << "\n--- 死亡原因分布 ---\n";
    vector<pair<int,int>> dv(deathCounts.begin(), deathCounts.end());
    sort(dv.begin(), dv.end(), [](const auto& a, const auto& b) { return a.second > b.second; });
    for (auto& p : dv) {
        if (G.count(p.first)) {
            string text = G[p.first].text;
            size_t pos = text.find("【死因：");
            string cause = "未知";
            if (pos != string::npos) {
                size_t end = text.find("】", pos);
                if (end != string::npos) cause = text.substr(pos+4, end-pos-4);
            }
            cout << "  " << cause << ": " << p.second
                 << " 次 (" << 100.0*p.second/deaths << "%)\n";
        }
    }
    cout << "========================================\n";
}

void showStats() {
    int decisionNodes = 0, endingNodes = 0, victoryNodes = 0;
    for (auto& [id, n] : G) {
        if (n.isEnding) { endingNodes++; if (n.isVictory) victoryNodes++; }
        else decisionNodes++;
    }
    cout << "\n========================================\n";
    cout << "  游戏数据统计\n";
    cout << "========================================\n";
    cout << "决策节点数: " << decisionNodes << " (每个 3 个选项)\n";
    cout << "结局节点数: " << endingNodes
         << " (死亡 " << (endingNodes - victoryNodes)
         << " / 胜利 " << victoryNodes << ")\n";
    cout << "总节点数:   " << G.size() << "\n";
    cout << "========================================\n";
}

int main(int argc, char* argv[]) {
    initAll();
    if (argc > 1 && strcmp(argv[1], "--sim") == 0) {
        int n = 100000;
        if (argc > 2) n = atoi(argv[2]);
        showStats();
        simulate(n);
        return 0;
    }
    if (argc > 1 && strcmp(argv[1], "--stats") == 0) {
        showStats();
        return 0;
    }
    playGame();
    return 0;
}
